#pragma once
#include <random>

namespace CommonUtilities
{
	template<class _RandomEngineTy, class _RandomGeneratorFunc>
	static void Seed(_RandomEngineTy& aRandomEngine, _RandomGeneratorFunc aFunc);

	template<class _RandomEngineTy, class _RandomGeneratorFunc>
	void Seed(_RandomEngineTy& aRandomEngine, _RandomGeneratorFunc aFunc)
	{
		typedef decltype(aFunc()) _RandomGenResultType;
		static_assert(sizeof(std::seed_seq::result_type) == sizeof(_RandomGenResultType));	// Seed Sequence must have same size elements as generated by _RandomGeneratorFunc.

		constexpr size_t byteSize = 8;
		constexpr size_t wordByteSize = _RandomEngineTy::word_size / byteSize;
		constexpr size_t stateByteSize = wordByteSize * _RandomEngineTy::state_size;
		constexpr size_t seedSize = stateByteSize / (sizeof(std::seed_seq::result_type));

		std::seed_seq::result_type seedData[seedSize] = {};
		std::generate_n(seedData, seedSize, std::ref(aFunc));

		std::seed_seq seed(seedData, seedData + seedSize);
		aRandomEngine.seed(seed);
	}
}